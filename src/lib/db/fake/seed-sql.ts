// Renders the demo data in seed.ts as supabase/seed.sql, so the fake and the local database hold
// the same leads, notes, history and files. Run `pnpm db:seed` after changing seed.ts or the engine;
// a test fails while the file is stale.
import { ADMINS, DEMO_USERS, seedTables } from './seed';

const HOTEL_USERS = [
  { ...DEMO_USERS.userA, fullName: 'Hotel user A' },
  { ...DEMO_USERS.userB, fullName: 'Hotel user B' },
];

const lit = (v: string | number | boolean | null | undefined): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${v.replace(/'/g, "''")}'`;
};
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const values = (rows: string[][]) => rows.map((r) => `  (${r.join(', ')})`).join(',\n');

export function renderSeedSql(): string {
  const t = seedTables();
  const people = [...ADMINS, ...HOTEL_USERS];
  // Admins join first, in team order: that order breaks ties when a new lead picks its owner.
  const joined = (i: number) => lit(new Date(Date.UTC(2026, 10, 1, 9, i)).toISOString());

  const out: string[] = [
    '-- GENERATED by `pnpm db:seed` from src/lib/db/fake/seed.ts. Do not edit by hand.',
    '-- Local development only: invented hotels, people and placeholder team emails.',
    '-- The demo users have no password; sign in with a magic link (Mailpit: http://127.0.0.1:54324).',
    '',
    '-- Historic rows: skip the triggers so the seeded history is not logged twice.',
    'set session_replication_role = replica;',
    '',
    'insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,',
    '  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,',
    '  confirmation_token, recovery_token, email_change_token_new, email_change) values',
    values(
      people.map((p, i) => [
        lit('00000000-0000-0000-0000-000000000000'), lit(p.id), lit('authenticated'), lit('authenticated'), lit(p.email), lit(''),
        joined(i), json({ provider: 'email', providers: ['email'] }), json({ full_name: p.fullName }), joined(i), joined(i),
        lit(''), lit(''), lit(''), lit(''),
      ]),
    ),
    'on conflict (id) do nothing;',
    '',
    'insert into auth.identities (id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at) values',
    values(
      people.map((p, i) => [
        lit(p.id), lit(p.id), lit(p.id), lit('email'), json({ sub: p.id, email: p.email, email_verified: true }), joined(i), joined(i), joined(i),
      ]),
    ),
    'on conflict do nothing;',
    '',
    'insert into public.profiles (id, role, full_name, created_at) values',
    values(people.map((p, i) => [lit(p.id), lit(p.role), lit(p.fullName), joined(i)])),
    'on conflict (id) do nothing;',
    '',
    'insert into public.projects (id, owner_id, hotel_name, inputs, results, engine_version, share_token, created_at, updated_at) values',
    values(
      t.projects.map((p) => [
        lit(p.id), lit(p.ownerId), lit(p.hotelName), json(p.inputs), json(p.results), lit(p.engineVersion), lit(p.shareToken), lit(p.createdAt), lit(p.updatedAt),
      ]),
    ),
    ';',
    '',
    'insert into public.leads (id, project_id, hotel_name, city, rooms, contact_name, email, phone, message, consent,',
    '  inputs, results, engine_version, status, owner_id, created_at) values',
    values(
      t.leads.map((l) => [
        lit(l.id), lit(l.projectId), lit(l.hotelName), lit(l.city), lit(l.rooms), lit(l.contactName), lit(l.email), lit(l.phone),
        lit(l.message), lit(l.consent), json(l.inputs), json(l.results), lit(l.engineVersion), lit(l.status), lit(l.ownerId), lit(l.createdAt),
      ]),
    ),
    ';',
    "select setval('public.lead_number_seq', (select max(substring(id from 3)::int) from public.leads));",
    '',
    'insert into public.lead_notes (lead_id, author_id, body, created_at) values',
    values(t.notes.map((n) => [lit(n.leadId), lit(n.authorId), lit(n.body), lit(n.createdAt)])),
    ';',
    '',
    'insert into public.lead_events (lead_id, kind, data, actor_id, created_at) values',
    values(t.events.map((e) => [lit(e.leadId), lit(e.kind), json(e.data), lit(e.actorId), lit(e.createdAt)])),
    ';',
    '',
    '-- The bytes are uploaded to Storage by `pnpm db:reset` (scripts/seed-storage.mts).',
    'insert into public.lead_files (lead_id, path, name, size, uploaded_by, created_at) values',
    values(t.files.map((f) => [lit(f.leadId), lit(f.path), lit(f.name), lit(f.size), lit(f.uploadedBy), lit(f.createdAt)])),
    ';',
    '',
    'set session_replication_role = origin;',
    '',
  ];
  return out.join('\n');
}
